package com.contentpilot.creative;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;

import static org.assertj.core.api.Assertions.assertThat;

class CreativeOverlayRendererTest {

    private final CreativeOverlayRenderer renderer = new CreativeOverlayRenderer();
    private final FallbackImageProvider imageProvider = new FallbackImageProvider();

    @Test
    @DisplayName("Should apply deterministic overlay with brand, price, badge, and CTA button without errors")
    void testApplyDeterministicOverlay() throws Exception {
        // Given a base image generated by the engine
        ImageGenerationRequest genReq = ImageGenerationRequest.builder()
                .prompt("Чашка капучино")
                .style("COFFEE_AESTHETIC")
                .aspectRatio("1:1")
                .brandName("Coffee Pilot")
                .build();

        ImageGenerationResult baseImage = imageProvider.generateImage(genReq);
        assertThat(baseImage.getImageBytes()).isNotEmpty();
        assertThat(baseImage.getWidth()).isEqualTo(1080);
        assertThat(baseImage.getHeight()).isEqualTo(1080);

        // When applying deterministic overlay
        byte[] compositedBytes = renderer.applyOverlay(
                baseImage.getImageBytes(),
                "Coffee Pilot",
                "320 ₽",
                "Сезонная новинка",
                "Попробовать",
                "BOTTOM_CENTER"
        );

        // Then output must be valid PNG image with identical dimensions
        assertThat(compositedBytes).isNotEmpty();
        BufferedImage resultImg = ImageIO.read(new ByteArrayInputStream(compositedBytes));
        assertThat(resultImg).isNotNull();
        assertThat(resultImg.getWidth()).isEqualTo(1080);
        assertThat(resultImg.getHeight()).isEqualTo(1080);
    }

    @Test
    @DisplayName("Should support vertical 9:16 format for Reels and Stories")
    void testVerticalAspectRatioOverlay() throws Exception {
        ImageGenerationRequest genReq = ImageGenerationRequest.builder()
                .prompt("Холодный айс-латте")
                .style("DARK_LUXURY")
                .aspectRatio("9:16")
                .brandName("Coffee Pilot")
                .build();

        ImageGenerationResult baseImage = imageProvider.generateImage(genReq);
        assertThat(baseImage.getWidth()).isEqualTo(1080);
        assertThat(baseImage.getHeight()).isEqualTo(1920);

        byte[] compositedBytes = renderer.applyOverlay(
                baseImage.getImageBytes(),
                "Coffee Pilot",
                "350 ₽",
                "Хит продаж",
                "Заказать",
                "BOTTOM_CENTER"
        );

        BufferedImage resultImg = ImageIO.read(new ByteArrayInputStream(compositedBytes));
        assertThat(resultImg).isNotNull();
        assertThat(resultImg.getWidth()).isEqualTo(1080);
        assertThat(resultImg.getHeight()).isEqualTo(1920);
    }
}
